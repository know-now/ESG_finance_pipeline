def test_esg_risk_logic():
    """Testing how converts sentiment into risk_score (logic from processor)"""
    model_score = 0.85
    
    #If model says NEGATIVE, risk should be high
    label_neg = "NEGATIVE"
    risk_neg = model_score if label_neg == 'NEGATIVE' else (1.0 - model_score)
    assert risk_neg == 0.85, "Risk for NEGATIVE is calculated wrong!"
    
    # If model says POSITIVE, risk should be low
    label_pos = "POSITIVE"
    risk_pos = model_score if label_pos == 'NEGATIVE' else (1.0 - model_score)
    assert round(risk_pos, 2) == 0.15, "Risk for POSITIVE is calculated wrong!"
    
def test_article_schema():
    """Testing if the data structure is correctly prepared for the Kafka/MinIO"""
    #Immitating the dictionary that is generated by scraper
    mock_article={
        'title': "Tesla faces new environmental lawsuit",
        "source": "https: //finance.yahoo.com",
        "timestamp": "2026-10-24 10:00:00",
        "summary": "Some text"
    }
    
    #Checking fields
    required_keys = ["title", "source", "timestamp", "summary"]
    for key in required_keys:
        assert key in mock_article, f"Needed field is not present: {key}"
        assert len(mock_article[key]) > 0, f"Field {key} can not be empty."
    